const fs = require('fs');
const path = require('path');
const queueFile='src/main/services/campaign-queue.service.ts';
const serviceSource='files/src/main/services/campaign/campaign-queue-runner.service.ts';
const serviceTarget='src/main/services/campaign/campaign-queue-runner.service.ts';
if(!fs.existsSync(queueFile)) throw new Error(`Dosya bulunamadı: ${queueFile}`);
fs.copyFileSync(queueFile,`${queueFile}.before-package-13g-36.bak`);
let source=fs.readFileSync(queueFile,'utf8');
